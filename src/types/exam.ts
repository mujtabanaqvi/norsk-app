/**
 * Shared Type Definitions for Norskprøven Oral Exam
 * Matches the Next.js control-plane schema, Zod validation, and turn-based exam engine.
 */

export type CefrLevel = 'B1' | 'B2';

export type CoCandidateMode = 'AI_PEER' | 'HUMAN_LOCAL';

export type ExamSessionStatus = 'ACTIVE' | 'COMPLETED' | 'FAILED';

export type SpeakerRole =
  | 'EXAMINER'
  | 'AI_COCANDIDATE'
  | 'CANDIDATE_1'
  | 'CANDIDATE_2';

/**
 * Exam Topic entity retrieved from the backend catalog
 */
export interface ExamTopic {
  id: string;
  slug: string;
  titleNo: string;
  level: CefrLevel;
  monologuePromptNo: string;
  discussionPromptNo: string;
  followUpQuestionsNo: string[];
  isActive?: boolean;
  createdAt?: string | Date;
}

/**
 * Exam theme (category grouping many question sets) from GET /api/exam/topics
 */
export interface ExamTheme {
  id: string;
  slug: string;
  titleNo: string;
  descriptionNo: string | null;
  /** Number of active question sets per level */
  setCounts: Record<CefrLevel, number>;
}

/**
 * Transcript turn stored and displayed during active exam sessions
 */
export interface TranscriptTurn {
  id?: string;
  speaker: string;
  role: SpeakerRole;
  text: string;
  timestamp: number;
  stage?: string;
  durationMs?: number;
  isFinal?: boolean;
}

/**
 * Single AI reply turn returned by /api/exam/start or /api/exam/[sessionId]/turn
 */
export interface ExamReply {
  index: number;
  speaker: 'examiner' | 'co_candidate';
  role: 'EXAMINER' | 'AI_COCANDIDATE';
  text: string;
  audioUrl: string;
}

/**
 * Criterion score matching HK-dir B1/B2 rubric evaluation
 */
export interface CriterionScore {
  score: number; // 1 - 10
  feedbackNo: string;
  feedbackEn: string;
}

/**
 * Concrete Norwegian correction item generated by rubric evaluator
 */
export interface ConcreteCorrection {
  originalQuote: string;
  correctedNorwegian: string;
  grammarOrVocabRule: string;
}

export type AssessedLevel = 'Under B1' | 'B1' | 'B2' | 'Over B2';

/**
 * Detailed candidate evaluation scorecard for each participant
 */
export interface CandidateEvaluation {
  speakerRole: 'CANDIDATE_1' | 'CANDIDATE_2';
  targetLevel: CefrLevel;
  assessedLevel: AssessedLevel;
  passedTargetLevel: boolean;
  overallSummaryNo: string;
  overallSummaryEn: string;
  criteriaScores: {
    formidlingOgFlyt: CriterionScore;
    uttaleOgForstaelighet: CriterionScore;
    ordforrad: CriterionScore;
    grammatikkOgSetningsstruktur: CriterionScore;
  };
  concreteCorrections: ConcreteCorrection[];
}

/**
 * Complete post-exam evaluation stored in Neon PostgreSQL
 */
export interface ExamEvaluation {
  candidates: CandidateEvaluation[];
  evaluatedAt?: string;
  insufficientData?: boolean;
  notes?: string;
}

/**
 * User quota information from /api/exam/topics or /api/quota
 */
export interface UserQuota {
  remainingAudioSeconds: number;
  totalCostUsd?: string;
}

/**
 * GET /api/exam/topics response payload
 */
export interface GetTopicsResponse {
  themes: ExamTheme[];
  quota: UserQuota;
}

/**
 * POST /api/exam/start request payload
 */
export interface StartExamRequest {
  userId?: string;
  /** Theme id/slug, or 'RANDOM' to compose the exam across random themes */
  themeId?: string;
  /** @deprecated Legacy: a specific question set id/slug */
  topicId?: string;
  level: CefrLevel;
  coCandidateMode: CoCandidateMode;
}

/**
 * Exam phase for Norskprøven oral test structure
 */
export type ExamStage = 'DEL_1' | 'DEL_2' | 'DEL_3' | 'DONE';

/**
 * POST /api/exam/start response payload
 */
export interface StartExamResponse {
  sessionId: string;
  stage: ExamStage;
  done: boolean;
  transcript: TranscriptTurn[];
  replies: ExamReply[];
  topic: {
    id: string;
    titleNo: string;
    monologuePromptNo: string;
    discussionPromptNo: string;
    followUpQuestionsNo: string[];
  };
  theme?: { id: string; titleNo: string } | null;
}

/**
 * POST /api/exam/[sessionId]/turn response payload
 */
export interface TurnResponse {
  sessionId: string;
  retry?: boolean;
  stage: ExamStage;
  done: boolean;
  candidateText: string;
  transcript: TranscriptTurn[];
  replies: ExamReply[];
  message?: string;
}

/**
 * POST /api/exam/[sessionId]/finish response payload
 */
export interface FinishExamResponse {
  sessionId: string;
  status: ExamSessionStatus;
}

/**
 * React Navigation Stack parameter list
 */
export type RootStackParamList = {
  ExamSetup: undefined;
  ExamRoom: {
    sessionId: string;
    level: CefrLevel;
    coCandidateMode: CoCandidateMode;
    topicTitle: string;
    monologuePromptNo?: string;
    discussionPromptNo?: string;
    initialReplies: ExamReply[];
    initialTranscript: TranscriptTurn[];
  };
  ExamResults: {
    sessionId: string;
  };
  Auth: undefined;
  Subscription: undefined;
  Referral: undefined;
  HowTo: undefined;
  Terms: undefined;
  PrivacyPolicy: undefined;
};

/**
 * Usage ledger entry stored per exam session
 */
export interface UsageLedgerEntry {
  id?: string;
  sessionId: string;
  userId: string;
  source: 'REALTIME_VOICE_AGENT' | 'POST_EXAM_RUBRIC_EVAL' | string;
  llmModel: string;
  llmPromptTokens: number;
  llmCompletionTokens: number;
  ttsCharacters: number;
  sttAudioSeconds: string | number;
  estimatedCostUsd: string;
  createdAt?: string | Date;
}

/**
 * GET /api/exam/[sessionId]/results response payload
 */
export interface ExamResultsResponse {
  status: ExamSessionStatus;
  level: CefrLevel;
  coCandidateMode: CoCandidateMode;
  transcriptJson: TranscriptTurn[];
  evaluationJson: ExamEvaluation | null;
  usage: UsageLedgerEntry[];
  topic: ExamTopic | null;
  error?: string;
  message?: string;
}
